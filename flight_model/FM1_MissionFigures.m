function FM1_MissionFigures(ms,ac,in)
L=ms.log; t=L.t;
rho=FM1_Atmosphere(max(L.h,0));
q=0.5*rho.*L.V.^2;
CD=L.D./max(q*ac.S,1e-3);
LD=L.CL./max(CD,1e-3);
alpha=(L.CL - ac.CL0)/ac.CLa*180/pi;
gam=asind(max(min(L.ROC./max(L.V,1),1),-1));
theta=alpha + gam;
soc=(1 - L.Ah_/in.batt.Q_Ah)*100;
cl=L.CL; onG=L.phase==1 | L.phase==9;
LDp=LD; LDp(L.V<3)=NaN;
Pth=L.T.*L.V;
list={ ...
 'M01_Altitude',L.h,{'Height'},'Height above ground (m)','Altitude'; ...
 'M02_Airspeed',L.V,{'Airspeed'},'Airspeed (m/s)','Airspeed'; ...
 'M03_Distance_Flown',L.x/1000,{'Path distance'},'Distance (km)','Total path distance flown'; ...
 'M04_Rate_of_Climb',L.ROC,{'ROC'},'Rate of climb (m/s)','Rate of climb'; ...
 'M05_Flight_Path_Angle',gam,{'Gamma'},'Flight path angle (deg)','Flight path angle'; ...
 'M06_Thrust_and_Drag',{L.T,L.D},{'Thrust','Drag'},'Force (N)','Thrust and drag'; ...
 'M07_Lift_Coefficient',{cl,ac.CL_max},{'CL','CLmax'},'Lift coefficient','Lift coefficient against CLmax'; ...
 'M08_Drag_Coefficient',CD,{'CD'},'Drag coefficient','Drag coefficient'; ...
 'M09_Lift_to_Drag',LDp,{'L/D'},'L/D','Lift-to-drag ratio'; ...
 'M10_Angle_of_Attack',alpha,{'Alpha'},'Angle of attack (deg)','Angle of attack'; ...
 'M11_Pitch_Attitude',theta,{'Theta'},'Pitch attitude (deg)','Pitch attitude (alpha + gamma)'; ...
 'M12_Dynamic_Pressure',q,{'q'},'Dynamic pressure (Pa)','Dynamic pressure'; ...
 'M13_Air_Density',rho,{'rho'},'Air density (kg/m3)','Air density'; ...
 'M14_Battery_Power',L.P,{'Battery power'},'Power (W)','Battery power'; ...
 'M15_Power_Flow',{L.P,L.P_shaft,Pth},{'Battery','Shaft','Thrust power (T.V)'},'Power (W)','Power from battery to thrust'; ...
 'M16_Battery_Current',L.I_b,{'Battery current'},'Current (A)','Battery current'; ...
 'M17_Motor_Current',{L.I_m,in.mot.I_max},{'Motor current','Motor limit'},'Current (A)','Motor current against its limit'; ...
 'M18_Battery_Voltage',L.V_b,{'Battery voltage'},'Voltage (V)','Battery voltage under load'; ...
 'M19_State_of_Charge',{soc,in.batt.SoC_min*100},{'SoC','Reserve limit'},'State of charge (%)','State of charge (below the limit = beyond the allowed battery use)'; ...
 'M20_Energy_Used',{L.Wh_,ms.E_usable},{'Energy used','Usable energy'},'Energy (Wh)','Energy used against usable energy'; ...
 'M21_Charge_Used',L.Ah_*1000,{'Charge used'},'Charge (mAh)','Charge used'; ...
 'M22_Throttle',L.d*100,{'Throttle'},'Throttle (%)','Throttle'; ...
 'M23_Motor_RPM',L.RPM,{'RPM'},'RPM','Motor and propeller RPM'; ...
 'M24_Advance_Ratio',L.J,{'J'},'Advance ratio J','Propeller advance ratio'; ...
 'M25_Propeller_Efficiency',L.eta_p,{'eta_p'},'Efficiency','Propeller efficiency, including the installation loss'; ...
 'M26_Mass',L.m,{'Mass'},'Mass (kg)','Aircraft mass'};
for k=1:size(list,1)
    FM1_TimePlot(t,list{k,2},list{k,3},ms,list{k,5},list{k,4},list{k,1},list{k,5},in);
end
edges=[0 cumsum(ms.ph_t)];
FM1_TimePlot(t,L.V,{'Airspeed'},ms,'Take-off and first climb: airspeed','Airspeed (m/s)','M27_Takeoff_Zoom_Speed','Take-off close-up, airspeed',in,[0 edges(3)+15]);
FM1_TimePlot(t,L.h,{'Height'},ms,'Take-off and first climb: height','Height (m)','M28_Takeoff_Zoom_Height','Take-off close-up, height',in,[0 edges(3)+15]);
FM1_TimePlot(t,L.V,{'Airspeed'},ms,'Approach and landing: airspeed','Airspeed (m/s)','M29_Landing_Zoom_Speed','Landing close-up, airspeed',in,[edges(8)-10 edges(end)]);
FM1_TimePlot(t,L.h,{'Height'},ms,'Approach and landing: height','Height (m)','M30_Landing_Zoom_Height','Landing close-up, height',in,[edges(8)-10 edges(end)]);
tr=FM1_Track(ms,in); col=FM1_PhaseColors()*0.75;
f=figure('Color','w','Position',[60 60 1200 560]); hold on; hh=[];
for k=1:9
    i=L.phase==k; hh(k)=plot(L.x(i)/1000,L.h(i),'Color',col(k,:),'LineWidth',3);
end
grid on; box on; xlabel('Path distance (km)'); ylabel('Height (m)'); title('Mission profile: height against distance');
legend(hh,ms.phase,'Location','eastoutside'); FM1_SaveFig(f,'M31_Mission_Profile','Mission profile, height against path distance, by phase',in);
f=figure('Color','w','Position',[60 60 1200 700]); hold on;
for k=1:9
    i=L.phase==k; hh(k)=plot(tr.X(i)/1000,tr.Y(i)/1000,'Color',col(k,:),'LineWidth',2);
end
axis equal; grid on; box on; xlabel('X (km)'); ylabel('Y (km)'); title('Ground track (shape is illustrative in a point-mass model)');
legend(hh,ms.phase,'Location','eastoutside'); FM1_SaveFig(f,'M32_Ground_Track','Ground track, by phase',in);
f=figure('Color','w','Position',[60 60 1200 760]); hold on;
for k=1:9
    i=L.phase==k; hh(k)=plot3(tr.X(i)/1000,tr.Y(i)/1000,L.h(i),'Color',col(k,:),'LineWidth',2);
end
view([-35 28]); grid on; box on; xlabel('X (km)'); ylabel('Y (km)'); zlabel('Height (m)'); title('3D mission path (shape is illustrative in a point-mass model)');
legend(hh,ms.phase,'Location','eastoutside'); FM1_SaveFig(f,'M33_3D_Path','3D mission path, by phase',in);
c8=FM1_PhaseColors();
barset={ms.ph_Wh,'Energy (Wh)','Energy used in each phase','M34_Energy_by_Phase'; ...
          ms.ph_t,'Time (s)','Time in each phase','M35_Time_by_Phase'; ...
          ms.ph_Pavg,'Power (W)','Average battery power in each phase','M36_Power_by_Phase'};
for b=1:3
    f=figure('Color','w','Position',[60 60 1100 520]); hold on; v=barset{b,1};
    for k=1:9
        patch(k+[-.38 .38 .38 -.38],[0 0 v(k) v(k)],c8(k,:),'EdgeColor',[.3 .3 .3]);
        text(k,v(k),sprintf('%.1f',v(k)),'HorizontalAlignment','center','VerticalAlignment','bottom');
    end
    set(gca,'XTick',1:9,'XTickLabel',ms.phase,'XTickLabelRotation',20); xlim([0.4 9.6]); ylim([0 max(v)*1.15]);
    ylabel(barset{b,2}); title(barset{b,3}); grid on; box on;
    FM1_SaveFig(f,barset{b,4},barset{b,3},in);
end
end
